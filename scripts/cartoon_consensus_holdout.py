"""Precommitted independent 5m30-5m55 original cartoon film evaluation.

Both baseline MAX and new two-reference harmonic-mean consensus are computed
from the EXACT SAME Grounding DINO boxes and DINOv2 vectors, no second
inference/randomness. Parameters, reference images and movie timestamps are
locked before evaluating this previously unseen film excerpt.

Ground truth is deliberately unspecified until a human inspects the output.
No automatic PASS based solely on Buck candidates. Do not tune from results.
"""
from __future__ import annotations
import hashlib
import json
import subprocess
from pathlib import Path

import cv2
from PIL import Image, ImageDraw

from scripts.cartoon_full_film_holdout import FULL_MOVIE
from scripts.cartoon_holdout_eval import LOCKED_PARAMETERS
from scripts.cartoon_consensus_match import evaluate_consensus
from scripts.cartoon_video_recognize import ROOT, run

OUT = ROOT / "reports/cartoon-5m30-consensus-holdout"
PRECOMMITTED_FILM_SECOND = 330
DURATION = 25
FROZEN_CROP_DIR = ROOT / "reports/cartoon-reference-fixtures"


def get_excerpt() -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    output = OUT / "original_film_5m30_to_5m55.mp4"
    if output.is_file() and output.stat().st_size > 150_000:
        return output
    command = [
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
        "-ss", "00:05:30", "-i", FULL_MOVIE, "-t", str(DURATION),
        "-an", "-vf", "scale=640:-2",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "26",
        "-movflags", "+faststart", str(output),
    ]
    response = subprocess.run(command, capture_output=True, text=True,
                              timeout=240)
    if response.returncode:
        output.unlink(missing_ok=True)
        raise RuntimeError("Failed HLS movie excerpt: "+response.stderr[-700:])
    reader = cv2.VideoCapture(str(output))
    duration = (reader.get(cv2.CAP_PROP_FRAME_COUNT) /
                max(reader.get(cv2.CAP_PROP_FPS), 1))
    reader.release()
    if not (20 <= duration <= 27):
        raise RuntimeError(f"Video excerpt length mismatch: {duration:.2f}")
    return output


def make_contact(raw: dict, consensus: dict, directory: Path):
    assert len(raw["frames"]) == len(consensus["frames"])
    rows = (len(raw["frames"])+3)//4
    sheet = Image.new("RGB", (360*4, rows*260), "white")
    pen = ImageDraw.Draw(sheet)
    for i,(a,b) in enumerate(zip(raw["frames"],consensus["frames"])):
        assert a["second"] == b["second"]
        t = a["second"]
        imagefile = directory / "frames" / f"t{t:.2f}.jpg"
        # Renderer uses ORIGINAL video boxes (auto-generated by detector).
        bgr = cv2.imread(str(imagefile))
        if bgr is None:
            raise RuntimeError(f"Model didn't produce expected evidence frame {t}")
        for box in b["proposals"]:
            if box["raw_buck_candidate"] and not box["consensus_buck_candidate"]:
                x0,y0,x1,y1 = box["box_xyxy"]
                cv2.rectangle(bgr,(x0,y0),(x1,y1),(255,0,255),3)
                cv2.putText(bgr, "REJECTED BY CONSENSUS",
                    (x0,max(y0-8,16)),cv2.FONT_HERSHEY_SIMPLEX,.45,
                    (255,0,255),1)
        img=Image.fromarray(cv2.cvtColor(bgr,cv2.COLOR_BGR2RGB))
        img.thumbnail((352,218))
        x=(i%4)*360;y=(i//4)*260
        sheet.paste(img,(x,y))
        pen.text((x+3,y+221),f"Film 5m30+{t:.1f}s / raw={b['raw_predicted_buck']}",fill="black")
        pen.text((x+3,y+239),f"two-pose consensus={b['consensus_predicted_buck']}",fill="black")
    sheet.save(OUT/"untuned_consensus_comparison.jpg",quality=93)


def main():
    movie=get_excerpt()
    references=[
        FROZEN_CROP_DIR/"reference_auto_crop.jpg",
        FROZEN_CROP_DIR/"reference_auto_crop_buck_bow.jpg",
    ]
    for image in references:
        if not image.is_file():
            raise FileNotFoundError(f"Frozen pretrained-model auto crop missing: {image}")
    directory=OUT/"raw"
    data=run(movie,directory,interval=2.5,max_frames=10,
             box_threshold=LOCKED_PARAMETERS["box_threshold"],
             match_threshold=LOCKED_PARAMETERS["match_threshold"],
             reference_crops=references)
    consensus=evaluate_consensus(data)
    (OUT/"consensus_result.json").write_text(
        json.dumps(consensus,indent=2,ensure_ascii=False),encoding="utf-8")
    make_contact(data,consensus,directory)
    summary={
        "status":"MEASURED_UNLABELED",
        "film_source":FULL_MOVIE,
        "precommitted_time_window_in_full_film":[PRECOMMITTED_FILM_SECOND,
                                                  PRECOMMITTED_FILM_SECOND+DURATION],
        "excerpt_sha256":hashlib.sha256(movie.read_bytes()).hexdigest(),
        "baseline_method":"max of same two Buck pose features >= 0.42",
        "new_method":"harmonic mean of same two Buck pose features >= 0.42",
        "rule_frozen_before_first_exposure":True,
        "formula_selection_used_earlier_development_errors":True,
        "no_new_model_training_or_threshold_changes":True,
        "unchanged_detector_boxes":True,
        "sampled_frame_count":len(data["frames"]),
        "A_original_max_timestamps":consensus["raw_positive_timestamps"],
        "B_consensus_timestamps":consensus["consensus_positive_timestamps"],
        "original_positive_frames_rejected_by_B":
            consensus["original_positive_frames_rejected_by_consensus"],
        "needs_post_inference_human_truth_before_precision_recall":True,
    }
    (OUT/"summary.json").write_text(
        json.dumps(summary,indent=2,ensure_ascii=False),encoding="utf-8")
    print(json.dumps(summary,indent=2,ensure_ascii=False),flush=True)
    return 0


if __name__=="__main__":
    raise SystemExit(main())
